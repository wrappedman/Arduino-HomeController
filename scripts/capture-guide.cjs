// Capture real pixels from the current locally served UI. No mockups or compositing.
// CHROMIUM_PATH=/path/to/chromium BASE_URL=http://127.0.0.1:4173 npm run screenshots
const { chromium } = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.BASE_URL || 'http://127.0.0.1:4173';
const executablePath = process.env.CHROMIUM_PATH;
if (!executablePath) throw Error('Set CHROMIUM_PATH to an installed Chromium binary.');
const output = path.join(__dirname, '../data/guide');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const capture = async name => {
    await page.screenshot({ path: path.join(output, name + '.jpg'), type: 'jpeg', quality: 83, animations: 'disabled' });
    console.log('Captured', name);
  };
  try {
    await page.goto(base, { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('.hero');
    await page.evaluate(() => localStorage.removeItem('shap_demo_v2'));
    await page.reload();
    await page.waitForSelector('.hero');
    await capture('04-overview');
    await page.locator('.sidebar [data-nav="settings"]').click();
    await page.locator('[data-action="setup-preview"]').click();
    await capture('01-welcome');
    await page.locator('#setup-form button[type="submit"]').click();
    await page.locator('#f-ssid').fill('MyHome-WiFi');
    await capture('02-network');
    await page.locator('#f-wifiPassword').fill('example-password');
    await page.locator('#setup-form button[type="submit"]').click();
    await capture('03-admin');
    await page.locator('[data-action="setup-skip"]').click();
    await page.locator('.sidebar [data-nav="devices"]').click();
    await page.locator('[data-action="add:devices"]').click();
    await page.locator('#modal-form [name="name"]').fill('Hallway relay');
    await page.locator('#modal-form [name="pin"]').fill('14');
    await capture('05-device');
    await page.locator('#modal-form button[type="submit"]').click();
    await page.locator('#modal-root').waitFor({state:'detached'});
    await page.locator('.sidebar [data-nav="hardware"]').click();
    await page.locator('[data-pin="14"]').click();
    await capture('06-gpio');
    await page.locator('.sidebar [data-nav="designer"]').click();
    await page.locator('[data-widget-type="label"]').click();
    await page.locator('[data-prop="title"]').fill('My custom room');
    await page.locator('[data-prop="title"]').dispatchEvent('change');
    await capture('07-designer');
    await page.locator('[data-action="publish"]').click();
    await page.locator('.published-grid').waitFor();
    assert.match(await page.locator('.published-grid').innerText(), /My custom room/);
    await capture('08-published');
    await page.reload();
    await page.locator('.published-grid').waitFor();
    assert.match(await page.locator('.published-grid').innerText(), /My custom room/);
    const control = page.locator('[data-published-widget="w1"] [data-command="living"]');
    const pressed = await control.getAttribute('aria-pressed');
    await control.click();
    await page.waitForFunction(({ old }) => document.querySelector('[data-published-widget="w1"] [data-command="living"]')?.getAttribute('aria-pressed') !== old, { old: pressed });
    await page.locator('.sidebar [data-nav="automations"]').click();
    await page.locator('[data-action="add:automations"]').click();
    await capture('09-automation');
    await page.locator('[data-action="close-modal"]').click();
    await page.locator('.sidebar [data-nav="settings"]').click();
    await capture('10-settings');
    const authPage = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    await authPage.route('**/api/bootstrap', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{"setup":false,"version":"0.1.0-preview"}' }));
    await authPage.route('**/api/auth/session', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{"authenticated":false}' }));
    await authPage.goto(base, { waitUntil: 'domcontentloaded' });
    await authPage.locator('#login-form').waitFor();
    await authPage.screenshot({ path: path.join(output, '04-login.jpg'), type: 'jpeg', quality: 83 });
    await authPage.close();
    console.log('Captured 04-login');
    assert.deepEqual(errors, []);
    console.log('Browser interaction test passed: registration, publish, reload persistence, mapped command.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
