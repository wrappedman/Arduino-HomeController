"""Build a self-contained Arduino IDE sketch with all web assets in program flash.
Run before committing UI/firmware edits; the exported sketch requires no filesystem uploader.
"""
from pathlib import Path
import gzip
import hashlib
import shutil

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data'
SRC = ROOT / 'src'
SKETCH = ROOT / 'arduino' / 'SHAP'
SKETCH.mkdir(parents=True, exist_ok=True)

# Only generated/known files are overwritten. Never delete the user's other files.
for file in sorted(SRC.iterdir()):
    if file.is_file() and file.suffix in ('.cpp', '.h') and file.name != 'EmbeddedAssets.cpp':
        shutil.copyfile(file, SKETCH / file.name)
(SKETCH / 'SHAP.ino').write_text('// Open this file in Arduino IDE, select ESP32S3 Dev Module N16R8 and press Upload.\n#include "Platform.h"\n')

files = sorted(p for p in DATA.rglob('*') if p.is_file())
entries = []
with (SRC / 'EmbeddedAssets.cpp').open('w') as out:
    out.write('// GENERATED by scripts/export_arduino.py. Do not hand-edit.\n#include "EmbeddedAssets.h"\nnamespace shap {\n')
    for i, file in enumerate(files):
        suffix = file.suffix.lower()
        mime = {'.html':'text/html; charset=utf-8', '.css':'text/css; charset=utf-8', '.js':'application/javascript',
                '.svg':'image/svg+xml', '.jpg':'image/jpeg', '.woff2':'font/woff2', '.txt':'text/plain; charset=utf-8'}[suffix]
        contents = file.read_bytes()
        compressed = suffix in ('.html','.css','.js','.svg','.txt')
        blob = gzip.compress(contents, compresslevel=9, mtime=0) if compressed else contents
        identifier = f'asset_{i}'
        out.write(f'// /{file.relative_to(DATA).as_posix()} sha256={hashlib.sha256(contents).hexdigest()}\n')
        out.write(f'const uint8_t {identifier}[] PROGMEM = {{\n')
        for offset in range(0,len(blob),32):
            out.write('  ' + ','.join(f'0x{value:02x}' for value in blob[offset:offset+32]) + ',\n')
        out.write('};\n')
        entries.append((f'/{file.relative_to(DATA).as_posix()}',mime,identifier,len(blob),compressed))
    out.write('static const EmbeddedAsset assets[] = {\n')
    for path,mime,identifier,length,compressed in entries:
        out.write(f'  {{"{path}","{mime}",{identifier},sizeof({identifier}),{str(compressed).lower()}}},\n')
    out.write('};\nconst EmbeddedAsset* findEmbeddedAsset(const String& path) {\n')
    out.write('  for (const auto& asset : assets) if (path==asset.path) return &asset;\n  return nullptr;\n}\n}\n')
shutil.copyfile(SRC / 'EmbeddedAssets.cpp', SKETCH / 'EmbeddedAssets.cpp')
print(f'Exported {len(entries)} offline assets ({sum(n for *_,n,_ in entries):,} flash bytes) and sketch to {SKETCH.relative_to(ROOT)}')
